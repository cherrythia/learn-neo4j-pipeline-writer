"""Render the MySQL init script from ``demo_env.data``.

Regenerate after changing demo data:  ``uv run python -m demo_env.seed_sql``
"""

from __future__ import annotations

from dataclasses import astuple
from datetime import date
from pathlib import Path

from demo_env.data import ROWS, columns_of

SEED_PATH = Path("infra/mysql/init/01_seed.sql")

_DDL = {
    "issuers": """CREATE TABLE issuers (
  issuer_id INT PRIMARY KEY,
  name VARCHAR(200) NOT NULL,
  ticker VARCHAR(10) NOT NULL UNIQUE,
  sector VARCHAR(100) NOT NULL,
  board VARCHAR(20) NOT NULL,
  country CHAR(2) NOT NULL
);""",
    "rules": """CREATE TABLE rules (
  rule_code VARCHAR(20) PRIMARY KEY,
  title VARCHAR(200) NOT NULL,
  text TEXT NOT NULL,
  filing_type VARCHAR(30) NOT NULL
);""",
    "obligations": """CREATE TABLE obligations (
  obligation_id INT PRIMARY KEY,
  rule_code VARCHAR(20) NOT NULL REFERENCES rules(rule_code),
  board VARCHAR(20) NOT NULL,
  deadline_days INT NOT NULL
);""",
    "filings": """CREATE TABLE filings (
  filing_id VARCHAR(40) PRIMARY KEY,
  issuer_id INT NOT NULL REFERENCES issuers(issuer_id),
  filing_type VARCHAR(30) NOT NULL,
  fiscal_year INT NOT NULL,
  due_on DATE NOT NULL,
  filed_on DATE NOT NULL
);""",
}
_ORDER = ["issuers", "rules", "obligations", "filings"]


def _literal(value: object) -> str:
    if isinstance(value, bool):
        return "1" if value else "0"
    if isinstance(value, int):
        return str(value)
    if isinstance(value, date):
        return f"'{value.isoformat()}'"
    text = str(value).replace("\\", "\\\\").replace("'", "''")
    return f"'{text}'"


def render_demo_inserts() -> str:
    """DDL + INSERTs for the demo tables, in SQL that runs on both MySQL and SQLite."""
    out: list[str] = []
    for table in _ORDER:
        out.append(_DDL[table])
        cols = ", ".join(columns_of(table))
        values = ",\n  ".join(
            "(" + ", ".join(_literal(v) for v in astuple(row)) + ")"  # type: ignore[call-overload]
            for row in ROWS[table]
        )
        out.append(f"INSERT INTO {table} ({cols}) VALUES\n  {values};")
    return "\n\n".join(out) + "\n"


def render_seed_sql() -> str:
    return f"""-- GENERATED by `uv run python -m demo_env.seed_sql` from src/demo_env/data.py.
-- Do not edit by hand. All data is fictional.

-- Databases and users are created by 00_users.sh (passwords come from the environment).

USE demo_compliance;

{render_demo_inserts()}"""


def main() -> None:
    SEED_PATH.parent.mkdir(parents=True, exist_ok=True)
    SEED_PATH.write_text(render_seed_sql())
    print(f"wrote {SEED_PATH}")


if __name__ == "__main__":
    main()
